def explain_violation(violation: NormativeViolation) -> CodeExplanation:
    return VIOLATION_EXPLANATIONS.get(violation.code, GENERIC_VIOLATION_EXPLANATION)


def explain_module(module: str) -> str:
    return MODULE_LABELS.get(module, module)


def result_summary_lines(result: ProjectCalculationResult) -> list[str]:
    """Короткая сводка для окна после расчета: статус, число нарушений и ошибок модулей."""
    violations = result.all_violations
    lines: list[str] = []
    if result.is_compliant:
        lines.append("Проект соответствует проверенным нормам.")
    else:
        lines.append(f"Найдено нарушений: {len(violations)}.")
    if result.errors:
        lines.append(f"Модулей расчета с ошибками: {len(result.errors)}.")
    warnings = [issue for issue in result.issues if issue.severity == "warning"]
    if warnings:
        lines.append(f"Замечаний: {len(warnings)}.")
    return lines
